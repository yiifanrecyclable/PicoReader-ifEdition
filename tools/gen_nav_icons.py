"""Generate round-stroke Lucide masks from retained official SVG paths."""
import math
from pathlib import Path
from xml.etree import ElementTree
from svg.path import parse_path, Move

ROOT=Path(__file__).resolve().parents[1]
NAMES=('house','book-text','folder','sliders-horizontal')
SIZE=40
SAMPLES=4
def distance(p,a,b):
    v=b-a
    t=max(0,min(1,((p-a).real*v.real+(p-a).imag*v.imag)/(abs(v)**2))) if v else 0
    return abs(p-(a+t*v))
out=['/* Generated by tools/gen_nav_icons.py; do not edit.',' * Lucide artwork: ISC/MIT, see flash/licenses/LUCIDE-ISC.txt. */','#pragma once','#include <stdint.h>']
for name in NAMES:
    root=ElementTree.parse(ROOT/'assets/lucide-nav'/f'{name}.svg').getroot()
    lines=[]
    for element in root:
        for segment in parse_path(element.attrib['d']):
            if isinstance(segment,Move): continue
            steps=max(1,math.ceil(segment.length(error=1e-4)*4))
            points=[segment.point(i/steps) for i in range(steps+1)]
            lines.extend(zip(points,points[1:]))
    values=[]
    for y in range(SIZE):
        for x in range(SIZE):
            hits=0
            for dy in range(SAMPLES):
                for dx in range(SAMPLES):
                    p=complex((x+(dx+.5)/SAMPLES)*24/SIZE,(y+(dy+.5)/SAMPLES)*24/SIZE)
                    hits+=any(distance(p,a,b)<=1 for a,b in lines)
            values.append(round(hits*15/(SAMPLES*SAMPLES)))
    data=[(values[i]<<4)|values[i+1] for i in range(0,len(values),2)]
    out.append(f'static const uint8_t nav_{name.replace("-","_")}[{len(data)}]={{')
    for i in range(0,len(data),20):out.append('    '+','.join(f'0x{v:02x}' for v in data[i:i+20])+',')
    out.append('};')
(ROOT/'main/assets/nav_lucide.h').write_text('\n'.join(out)+'\n')
print('Generated 4 official Lucide masks, 40px, 16 gray coverage levels')
